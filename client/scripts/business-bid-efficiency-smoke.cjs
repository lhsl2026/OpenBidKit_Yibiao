// 本脚本只写独立临时 userData，模型和公司资料均为合成数据。
const { app, dialog } = require('electron');
const { Document, Packer, Paragraph, Table, TableRow, TableCell, Header } = require('docx');
const PizZip = require('pizzip');
const { createExportService } = require('../electron/services/exportService.cjs');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createSqliteDatabase } = require('../electron/services/sqliteDatabase.cjs');
const { createBusinessBidStore } = require('../electron/services/businessBidStore.cjs');
const { normalizeAnalysis } = require('../electron/services/businessBidDomain.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), '易标少填表验收-'));
app.setPath('userData', root);
let database;
app.whenReady().then(async () => {
  database = createSqliteDatabase(app);
  const store = createBusinessBidStore({ app, db: database.db });
  const empty = { directory:[],qualifications:[],disqualifications:[],fields:[],terms:[] };
  const fields = Array.from({length:12}, (_,i)=>({ title:i%2?'法定代表人姓名':'投标人名称',quote:'投标人名称 法定代表人姓名',section:`表单${i}` }));
  const analysis = normalizeAnalysis({ ...empty, fields }, { id:'synthetic',name:'合成',segment:1,text:'投标人名称 法定代表人姓名' });
  store.updateBusinessBidWithoutReload({ analysis, analysisComplete:true });
  const before = store.loadBusinessBid();
  assert.equal(before.formPlan.editableCount, 5);
  assert.ok(before.formPlan.reusedCount >= 11);
  store.saveReview({ fieldValues:{ representative:'甲方法人',purchaser:'合成采购人',delegate:'项目授权人' } });
  assert.equal(store.loadBusinessBid().companyProfiles['隆创信息有限公司'].representative,'甲方法人');
  assert.equal(store.loadBusinessBid().fieldValues[analysis.fields[1].id],'甲方法人');
  store.saveReview({ companyName:'贵州云界科创信息技术有限公司' });
  assert.equal(store.loadBusinessBid().formPlan.fields.find(x=>x.key==='representative').value,'');
  store.saveReview({ fieldValues:{ representative:'乙方法人' } });
  store.saveReview({ companyName:'隆创信息有限公司' });
  assert.equal(store.loadBusinessBid().formPlan.fields.find(x=>x.key==='representative').value,'甲方法人');
  assert.equal(store.loadBusinessBid().fieldValues.purchaser,undefined);
  assert.equal(store.loadBusinessBid().fieldValues.delegate,undefined);
  store.clear();
  assert.equal(store.loadBusinessBid().formPlan.fields.find(x=>x.key==='representative').value,'甲方法人');
  const raw = JSON.parse(database.db.prepare('SELECT state_json FROM business_bid_workspace WHERE id=1').get().state_json);
  assert.equal(raw.formPlan,undefined);
  const templatePath = path.join(root, '合成商务模板.docx');
  const doc = new Document({ sections:[{ headers:{ default:new Header({children:[new Paragraph('{项目名称}')]}) }, children:[
    new Paragraph('合成商务模板 · 非真实投标'),
    new Table({ rows: ['公司名称','法定代表人姓名','投标总价','Actual Signature','自定义说明'].map(label => new TableRow({ children:[new TableCell({children:[new Paragraph(label)]}),new TableCell({children:[new Paragraph(`{${label}}`)]})] })) }),
  ] }] });
  fs.writeFileSync(templatePath, await Packer.toBuffer(doc));
  store.updateBusinessBidWithoutReload({ analysis, analysisComplete:true });
  store.importTemplate(templatePath);
  assert.ok(store.loadBusinessBid().wordTemplate.fields.includes('公司名称'));
  store.saveReview({ projectName:'合成效率验收', analysisConfirmed:true,fieldValues:{'template:Actual Signature':'禁止自动写入','template:投标总价':'99999999'} });
  store.generateDraft();
  const exportPath = path.join(root, '合成模板导出.docx');
  dialog.showSaveDialog = async () => ({canceled:false,filePath:exportPath});
  const events = [];
  const exported = await createExportService().exportWord(store.getExportPayload('template'), value=>events.push(value));
  assert.equal(exported.success,true);
  const zip = new PizZip(fs.readFileSync(exportPath));
  const xml = zip.file('word/document.xml').asText();
  assert.ok(xml.includes('隆创信息有限公司') && xml.includes('甲方法人') && xml.includes('w:tbl'));
  assert.ok(xml.includes('待核实') && xml.includes('待人工填写') && !xml.includes('99999999') && !xml.includes('禁止自动写入'));
  assert.ok(zip.file(/word\/header\d+\.xml/).some(file=>file.asText().includes('合成效率验收')));
  assert.equal(events.at(-1).phase,'success');
  const storedTemplate = store.loadBusinessBid().wordTemplate.path;
  fs.appendFileSync(storedTemplate,'changed');
  assert.throws(()=>store.getExportPayload('template'),/模板已变化/);
  store.clearTemplate();
  assert.equal(store.loadBusinessBid().draft,null);
  assert.equal(store.loadBusinessBid().wordTemplate,null);
  database.close();
  console.log(JSON.stringify({success:true,beforeInputs:17,afterInputs:before.formPlan.editableCount,checks:20,synthetic:true,output:root}));
  app.exit(0);
}).catch(error=>{ console.error(error.stack); database?.close(); app.exit(1); });
